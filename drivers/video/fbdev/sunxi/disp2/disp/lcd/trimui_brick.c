/*
 * Panel driver for the TrimUI Brick (TG3040): one 1024x768 4-lane MIPI-DSI panel, sourced from
 * five different panel controllers. Vendor U-Boot probes which one is fitted and passes
 * "lcd=<model>" on the kernel command line; this driver sends that model's init sequence
 * (OTM1289A if there is no lcd=, JD9168 for names it doesn't know, both as stock does).
 *
 * Registered as "otm1289a" because that is the lcd_driver_name in TrimUI's device tree, which
 * vendor U-Boot also reads. Power-up timings, the model matching (unknown names get the JD9168
 * sequence) and the init sequences match TrimUI's stock kernel driver, recovered by
 * disassembly (research/panel_init_tables.txt holds the decoded tables).
 *
 * The display timings come from the device tree's lcd0 node, not from here.
 */

#include "trimui_brick.h"

/* An init-sequence entry: a MIPI DCS (Display Command Set) command with its parameters, a
 * delay (in cmd, ms) or the end of the sequence. */
struct panel_cmd {
	u8 cmd;
	u8 len;		/* number of parameters, or PANEL_DELAY_MS / PANEL_END */
	const u8 *para;
};

/* Markers in .len; real parameter counts are far below them. */
#define PANEL_DELAY_MS	0xfe
#define PANEL_END	0xff
#define CMD(c, ...)	{ c, sizeof((const u8[]){ __VA_ARGS__ }), (const u8[]){ __VA_ARGS__ } }
#define DELAY(ms)	{ ms, PANEL_DELAY_MS }
#define END		{ 0, PANEL_END }

/*
 * The tables are TrimUI's, copied verbatim (including entries whose purpose is unknown, such as
 * the repeated CMD(0xff, 0xff) in GC9702C). OTM1289A uses the Orise convention where command
 * 0x00 sets the register offset for the following write.
 */

